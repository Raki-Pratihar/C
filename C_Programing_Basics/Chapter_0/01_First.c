#include<stdio.h> //Pre prosser directive

int main(){
    printf("Hellow World"); // code for printing
    return 0; // end of the function
}

/* 🌟 Preprocessor directives are instructions that are processed before the actual compilation of a C program begins. They start with the # symbol.

Explanation:
* #include is a preprocessor directive.
* <stdio.h> is a standard header file that declares functions such as printf().
* The directive makes the header's declarations available to your program.

Important Points to Remember:
1. Preprocessor directives begin with #.

2. They generally do not end with a semicolon (;).

3. They are processed before the compiler translates the program into machine-level instructions.

4. #include and #define are two of the most commonly used directives.

⭐ Note: #include and #define are preprocessor directives, whereas printf() is a function.
*/